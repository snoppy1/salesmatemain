/**
 * ตรวจว่าข้อความลูกค้าเป็น "ภาษาอังกฤษล้วน" ไหม — ระบบยังไม่รองรับอังกฤษ
 * ถ้าใช่ จะไม่ให้ AI ตอบอัตโนมัติ แต่ขึ้น "รอตอบ" ให้คนจัดการเอง
 *
 * เกณฑ์: ไม่มีตัวอักษรไทยเลย และมีคำละติน ≥2 คำ หรือ ตัวอักษรละติน ≥5 ตัว
 * (คำสั้นๆ ที่คนไทยพิมพ์ปน เช่น "ok"/"gps", รหัสรุ่น "18650", ลิงก์ → ไม่นับเป็นอังกฤษ
 *  ส่วนเคสก้ำกึ่งเอียงไปทาง "รอตอบ" — คนตอบเองปลอดภัยกว่า AI ตอบไทยใส่ลูกค้าต่างชาติ)
 */
export function isMostlyEnglish(text: string): boolean {
  const t = (text || "").replace(/https?:\/\/\S+/g, " "); // ตัดลิงก์ออกก่อน
  if (/[฀-๿]/.test(t)) return false; // มีตัวไทยแม้ตัวเดียว = แชตไทย
  const latinWords = t.match(/[A-Za-z]{2,}/g) ?? [];
  const latinLetters = (t.match(/[A-Za-z]/g) ?? []).length;
  return latinWords.length >= 2 || latinLetters >= 5;
}

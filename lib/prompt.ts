export function buildUserContent(req: GenerateRequest): string {
  const rulesLines = req.rules
    .filter((r) => r.enabled !== false && r.trigger.trim() && r.partner.trim())
    .map((r) => {
      const price = r.price.trim() ? `${r.price.trim()} บาท` : "ไม่ระบุราคา";
      const promo = r.promo.trim() ? r.promo.trim() : "ไม่มี";
      return `- เมื่อลูกค้าสนใจ "${r.trigger.trim()}" → เสนอ "${r.partner.trim()}" (ราคา ${price}) | เหตุผล: ${r.reason.trim() || "-"} | โปร: ${promo}`;
    })
    .join("\n");

  const rulesBlock = rulesLines || "- (ยังไม่มีรายการคู่พ่วง)";

  const productLines = (req.products ?? [])
    .filter((p) => p.enabled !== false && p.name.trim())
    .map((p) => {
      const price = p.price.trim() ? ` (ราคา ${p.price.trim()} บาท)` : "";
      const desc = p.description.trim() ? ` — ${p.description.trim()}` : "";
      return `- ${p.name.trim()}${price}${desc}`;
    })
    .join("\n");

  const productsBlock = productLines || "- (ยังไม่มีข้อมูลสินค้า)";

  return `[ร้าน] ${req.shopName.trim() || "ไม่ระบุชื่อร้าน"}

[โทนการพูดของร้าน]
${req.shopVoice.trim() || "ไม่ระบุ"}

[รายการคู่พ่วงที่เสนอได้]
${rulesBlock}

[คลังสินค้า (ใช้แนะนำเมื่อไม่มีคู่พ่วงที่ตรง)]
${productsBlock}

[ข้อความ/บริบทจากลูกค้า]
${req.customerMsg.trim()}
(ในนี้อาจมีทั้งข้อความล่าสุดของลูกค้าและบริบท เช่น งบ/ของขวัญ/รีบ — ตีความเอง แล้วแอดมินกำลังจะตอบ)

วิเคราะห์แล้วตอบเป็น JSON ตามรูปแบบที่กำหนด`;
}


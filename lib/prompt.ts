/** ชื่อที่ AI เห็น: ฉบับล้างคำโฆษณาแล้ว (aiName) ถ้ามี — ชื่อจริงของร้านไม่โดนแตะ ใช้แสดงผล/แมตช์ออเดอร์ */
function aiSeenName(p: Product): string {
  return (p.aiName ?? "").trim() || p.name.trim();
}

/** บรรทัดสินค้าแบบเต็ม (ชื่อ+ราคา+สต็อก+คำอธิบาย) — ใช้ตอบเชิงลึก */
function fullProductLine(p: Product): string {
  const price = p.price.trim() ? ` (ราคา ${p.price.trim()} บาท)` : "";
  const desc = p.description.trim() ? ` — ${p.description.trim()}` : "";
  const stock = stockTag(p);
  return `- ${aiSeenName(p)}${price}${stock}${desc}`;
}

/**
 * ย่อชื่อสินค้าให้สั้นลงสำหรับ "ดัชนีย่อ" — ชื่อ Lazada มักยาวมาก (ยัด keyword/หางโฆษณาซ้ำๆ)
 * สเปกหลักมักอยู่ช่วงต้น จึงตัดที่ ~70 ตัวอักษร (ขอบคำ) เก็บสเปก ตัดน้ำ
 * ของที่ลูกค้าถามจะถูกดึงไป "บล็อกรายละเอียดเต็ม" (ชื่อเต็ม+คำอธิบาย) อยู่แล้ว ดัชนีจึงย่อได้ปลอดภัย
 */
function shortName(name: string, maxChars = 70): string {
  const n = name.trim().replace(/\s+/g, " ");
  if (n.length <= maxChars) return n;
  const slice = n.slice(0, maxChars);
  const lastSpace = slice.lastIndexOf(" ");
  return (lastSpace > maxChars * 0.6 ? slice.slice(0, lastSpace) : slice).trimEnd() + "…";
}

/** บรรทัดสินค้าแบบย่อ (ชื่อย่อ+ราคา+มี/หมด ไม่มีคำอธิบาย) — ใช้เป็นดัชนีว่ามีอะไรขาย/เสนอพ่วง */
function briefProductLine(p: Product): string {
  const price = p.price.trim() ? ` (ราคา ${p.price.trim()} บาท)` : "";
  return `- ${shortName(aiSeenName(p))}${price}${briefStockTag(p)}`;
}

/** สต็อกแบบมีตัวเลข (ตอบ "เหลือกี่ชิ้น") — ใช้ใน "สเปกเต็มของที่เกี่ยวกับคำถาม" (ฝั่งไม่แคช) */
function stockTag(p: Product): string {
  if (typeof p.stock !== "number") return "";
  return p.stock <= 0 ? " [สินค้าหมด]" : ` [คงเหลือ ${p.stock} ชิ้น]`;
}

/**
 * สต็อกแบบ "มี/หมด" (ไม่บอกจำนวน) — ใช้ใน "ดัชนีย่อ" ที่อยู่ในก้อนแคช
 * เหตุผล: ถ้าใส่จำนวนเป๊ะ พอขายของได้ 1 ชิ้น ตัวเลขเปลี่ยน → byte เปลี่ยน → แคชพังทั้งก้อน
 * (ร้านขายดีจะแคชพังทุกออเดอร์ = จ่ายเต็มตลอด). "มี/หมด" เปลี่ยนเฉพาะตอนข้าม 0 → แคชอยู่รอด
 * ส่วนจำนวนเป๊ะยังมีใน [รายละเอียด/สเปกของสินค้าที่เกี่ยวกับคำถาม] (ฝั่งไม่แคช) ตอบ "เหลือกี่ชิ้น" ได้
 */
function briefStockTag(p: Product): string {
  if (typeof p.stock !== "number") return "";
  return p.stock <= 0 ? " [สินค้าหมด]" : " [มีสต็อก]";
}

/**
 * แยก user content เป็น 2 ส่วนเพื่อทำ prompt caching + ลด token:
 * - stable: ร้าน + ความรู้ร้าน + คลังสินค้า + โปรฯ (ซ้ำทุกข้อความของร้านเดิม → แคชได้)
 * - customer: (สเปกสินค้าที่เกี่ยวกับคำถาม) + ข้อความลูกค้า (เปลี่ยนทุกครั้ง → ไม่แคช)
 *
 * ร้านสินค้าเยอะ: stable ใส่ "ดัชนีย่อทั้งคลัง" (ชื่อ+ราคา+สต็อก) แทนคำอธิบายเต็มทุกชิ้น
 * แล้วแนบ "สเปกเต็มเฉพาะสินค้าที่เกี่ยวกับคำถาม" ไว้ฝั่ง customer — AI ยังเห็นของครบ แต่ส่ง token น้อยลงมาก
 */
export function buildUserContentParts(req: GenerateRequest): {
  stable: string;
  promo: string; // แยกจาก stable เพื่อให้เป็น cache breakpoint คนละจุด — โปรเปลี่ยนไม่ล้างแคชดัชนีสินค้า
  customer: string;
} {
  const enabled = (req.products ?? []).filter(
    (p) => p.enabled !== false && p.name.trim(),
  );
  const { relevant, useRetrieval } = selectRelevantHybrid(
    enabled,
    req.customerMsg,
    req.queryEmbedding ?? null,
  );

  // ดัชนีย่อ: แยก "ของหมด" ไปไว้ส่วนท้ายแบบชื่ออย่างเดียว — AI ต้องรู้แค่ว่ามีตัวนี้อยู่แต่หมด
  // (ราคา/สเปกเต็มถูกส่งในบล็อกรายละเอียดฝั่งไม่แคชอยู่แล้วเมื่อลูกค้าถามถึง)
  // ร้านที่ของหมดเยอะ (เช่น 178/323) ดัชนีก้อนแคชเล็กลงมาก + AI ไม่หยิบของหมดไปเสนอพ่วง
  const isSoldOut = (p: Product) => typeof p.stock === "number" && p.stock <= 0;
  const soldOut = useRetrieval ? enabled.filter(isSoldOut) : [];
  const indexed = useRetrieval ? enabled.filter((p) => !isSoldOut(p)) : enabled;

  const catalogHeader = useRetrieval
    ? "[รายการสินค้าในคลัง (ชื่อ+ราคา+สต็อก — ใช้ดูว่ามีอะไรขาย/แนะนำของที่เข้าคู่เพื่อเสนอพ่วง; สเปกละเอียดดูที่ส่วน 'รายละเอียดสินค้าที่เกี่ยวข้อง')]"
    : "[คลังสินค้า (ใช้ตอบคำถาม + แนะนำสินค้าที่เข้ากัน)]";
  const catalogLines = (useRetrieval ? indexed.map(briefProductLine) : indexed.map(fullProductLine)).join("\n");
  const productsBlock =
    catalogLines || (soldOut.length ? "- (สินค้าพร้อมส่งหมดชั่วคราวทั้งร้าน)" : "- (ยังไม่มีข้อมูลสินค้า)");

  const soldOutBlock = soldOut.length
    ? `

[สินค้าที่ของหมดชั่วคราว (ทุกตัวในรายการนี้ของหมด สั่งซื้อตอนนี้ไม่ได้ — ลูกค้าถามถึง: บอกว่าของหมด; ถ้าจะเอ่ยถึงตัวไหนในรายการนี้ต้องระบุว่าของหมดเสมอ ห้ามพูดให้เข้าใจว่ามีของ ห้ามเสนอขาย/พ่วง; แนะนำตัวใกล้เคียงที่มีของจากรายการด้านบนแทนได้; ราคา/สเปกดูส่วน 'รายละเอียดสินค้าที่เกี่ยวข้อง' เมื่อลูกค้าถามเจาะจง)]
${soldOut.map((p) => `- ${shortName(aiSeenName(p), 50)}`).join("\n")}`
    : "";

  const promoLines = (req.promotions ?? [])
    .filter((p) => p.title.trim())
    .map((p) => {
      const scope = p.productScope.trim() || "ทุกชิ้น";
      const min = p.minSpend != null ? `${p.minSpend}` : "-";
      const code = p.code.trim() || "-";
      const cond = p.conditionsText.trim() || "-";
      return `- ${p.title.trim()} | ใช้กับ: ${scope} | ขั้นต่ำ ${min} บาท | โค้ด ${code} | เงื่อนไข: ${cond}`;
    })
    .join("\n");
  const promoBlock = promoLines || "- (ตอนนี้ไม่มีโปรโมชั่น)";

  // เพศ/คำลงท้ายของผู้ช่วย — deterministic (ขึ้นกับ req.shopGender เท่านั้น) เพื่อให้ stable ไบต์ตรง
  // default (undefined/ไม่ใช่ male) = หญิง คงพฤติกรรมเดิมของร้านที่ยังไม่ตั้งเพศ
  const genderLine =
    req.shopGender === "male"
      ? "ผู้ชาย — ลงท้ายด้วย ครับ เท่านั้น"
      : "ผู้หญิง — ลงท้ายด้วย ค่ะ/คะ เท่านั้น";

  const stable = `[ร้าน] ${req.shopName.trim() || "ไม่ระบุชื่อร้าน"}

[โทนการพูดของร้าน]
${req.shopVoice.trim() || "ไม่ระบุ"}

[เพศ/คำลงท้ายของผู้ช่วย]
${genderLine}

[สิ่งที่ร้านอยากให้ AI จำ (ข้อมูล/นโยบายร้าน — ใช้ตอบลูกค้าได้เลยถ้าตรงคำถาม)]
${(req.shopMemory ?? "").trim() || "ไม่ระบุ"}

${catalogHeader}
${productsBlock}${soldOutBlock}`;

  // ขึ้นต้นด้วย \n\n เพื่อให้ stable+promo ต่อกันแล้วได้ข้อความเดิมเป๊ะทุกไบต์ (คำตอบไม่เปลี่ยน)
  const promo = `

[โปรโมชั่นที่ใช้ได้ตอนนี้ (แนะนำได้เฉพาะที่ตรงเงื่อนไข + ใช้กับสินค้าที่ลูกค้าสนใจ ห้ามแต่งเอง)]
${promoBlock}`;

  // สเปกเต็มเฉพาะสินค้าที่เกี่ยวกับคำถามนี้ (ฝั่ง customer = ไม่แคช เพราะเปลี่ยนตามคำถาม)
  const detailsBlock =
    useRetrieval && relevant.length
      ? `[รายละเอียด/สเปกของสินค้าที่เกี่ยวกับคำถามล่าสุด (ใช้ตอบเชิงลึกได้เลย)]
${relevant.map(fullProductLine).join("\n")}

`
      : "";

  const customer = `${detailsBlock}[ข้อความ/บริบทจากลูกค้า]
${req.customerMsg.trim()}
(ในนี้อาจมีทั้งข้อความล่าสุดของลูกค้าและบริบท เช่น งบ/ของขวัญ/รีบ — ตีความเอง แล้วแอดมินกำลังจะตอบ)

วิเคราะห์แล้วตอบเป็น JSON ตามรูปแบบที่กำหนด`;

  return { stable, promo, customer };
}

export function buildUserContent(req: GenerateRequest): string {
  const { stable, promo, customer } = buildUserContentParts(req);
  return `${stable}${promo}\n\n${customer}`;
}

/** ประกอบประวัติแชตเป็น customerMsg ให้ AI (เน้นข้อความล่าสุดของลูกค้า) — ใช้ทั้ง draft/choices/auto */
export function buildConversationContext(
  customerName: string,
  channel: string,
  messages: { sender: "customer" | "admin"; text: string; kind?: "text" | "image"; imageUrl?: string }[],
): { text: string; imageUrls: string[] } {
  const history = messages
    .slice(-12)
    .map((m) => {
      const who = m.sender === "admin" ? "แอดมิน" : "ลูกค้า";
      const body = m.kind === "image" ? `[ส่งรูป]${m.text ? " " + m.text : ""}` : m.text;
      return `${who}: ${body}`;
    })
    .join("\n");
  // เอา url รูปจาก "ลูกค้า" ใน 3 ข้อความล่าสุด สูงสุด 4 รูป (คุมต้นทุน)
  const imageUrls = messages
    .slice(-3)
    .filter((m) => m.sender === "customer" && m.kind === "image" && m.imageUrl)
    .map((m) => m.imageUrl as string)
    .slice(-4);
  const text = `นี่คือประวัติแชตกับลูกค้า "${customerName}" (ช่องทาง ${channel}):
${history}

แอดมินกำลังจะตอบลูกค้าต่อจากข้อความล่าสุด ร่างข้อความตอบที่พร้อมส่งได้เลย`;
  return { text, imageUrls };
}


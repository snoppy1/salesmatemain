export function buildUrlImportContent(
  url: string,
  pageText: string,
  images: string[],
): string {
  const imgList = images.length
    ? images.map((u, i) => `${i + 1}. ${u}`).join("\n")
    : "(ไม่พบรูปในหน้า)";
  return `ลิงก์ต้นทาง: ${url}

[รายการ URL รูปที่เจอในหน้า]
${imgList}

[เนื้อหาหน้าเว็บ]
"""
${pageText.trim().slice(0, 60000)}
"""

ดึงข้อมูลสินค้าออกมา แล้วตอบเป็น JSON ตามรูปแบบที่กำหนด`;
}

